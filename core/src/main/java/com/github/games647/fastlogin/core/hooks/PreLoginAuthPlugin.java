package com.github.games647.fastlogin.core.hooks;

/**
 * Name-based authentication operations that may run before the platform's
 * {@code Player} object exists.
 *
 * <p>This is deliberately separate from {@link AuthPlugin}: only an auth plugin
 * whose API can approve a pre-join login may be used by the backend Floodgate
 * path. Implementations must keep the password out of logs and must report API
 * gaps instead of emulating login state through the database.
 */
public interface PreLoginAuthPlugin {

    /**
     * Checks whether an account exists for this player name.
     *
     * @param playerName the player name
     * @return true if the account exists
     * @throws Exception when the account state cannot be read
     */
    boolean isRegistered(String playerName) throws Exception;

    /**
     * Whether this auth plugin exposes a name-based force login that is safe
     * before the player joins.
     *
     * @return true when {@link #forceLoginFromProxy(String)} can be used
     */
    boolean isPreLoginForceLoginSupported();

    /**
     * Registers an account by name. The password is generated by the caller and
     * is never shown to a Bedrock player.
     *
     * @param playerName the player name
     * @param password the generated password
     * @return true when the account was created
     */
    boolean registerPlayer(String playerName, String password);

    /**
     * Requests name-based cleanup of an account created by this pre-login attempt.
     * An accepted request does not prove an asynchronous deletion has completed.
     *
     * @param playerName the name this attempt just registered
     * @return true if the cleanup request was accepted, false if unsupported or failed
     */
    boolean unregisterPlayer(String playerName);

    /**
     * Queues or approves a force login for a player who is not online yet.
     *
     * @param playerName the player name
     * @return true when the auth plugin accepted the request
     */
    boolean forceLoginFromProxy(String playerName);
}
